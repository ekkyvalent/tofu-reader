#!/usr/bin/env python3
"""Build a 1-bit logo header and a preview PNG from an SVG or PNG source.

The panel draws bitmaps without rotating bits, so the packed bitmap is
pre-rotated 90 degrees counter-clockwise; the preview undoes that rotation
so it shows the image the way it appears on the device.
"""

import argparse
import io
import math
import os
import sys


def load_source_image(path, size):
    from PIL import Image

    ext = os.path.splitext(path)[1].lower()
    if ext == '.svg':
        import cairosvg

        with open(path, 'rb') as f:
            svg_data = f.read()
        png_bytes = cairosvg.svg2png(
            bytestring=svg_data, output_width=size, output_height=size)
        img = Image.open(io.BytesIO(png_bytes))
    else:
        img = Image.open(path)

    img = img.convert('RGBA')
    background = Image.new('RGBA', img.size, (255, 255, 255, 255))
    background.paste(img, mask=img.split()[3])
    img = background.convert('L')
    img = img.resize((size, size), Image.LANCZOS)
    img = img.rotate(90, expand=True)
    return img


def pack_bitmap(img, threshold):
    width, height = img.size
    pixels = img.tobytes()
    packed = []
    for y in range(height):
        for x in range(0, width, 8):
            byte = 0
            for b in range(8):
                if x + b < width:
                    bit = 1 if pixels[y * width + x + b] >= threshold else 0
                    byte |= bit << (7 - b)
            packed.append(byte)
    return bytes(packed), width, height


def render_header(packed, width, height, source_name, array_name):
    lines = [
        '#pragma once',
        '#include <cstdint>',
        '',
        '// Generated by scripts/build-logo.py from '
        f'{source_name}. Do not edit.',
        f'// Image dimensions: {width}x{height}',
        f'static const uint8_t {array_name}[] = {{',
    ]
    for i in range(0, len(packed), 16):
        chunk = ', '.join(f'0x{v:02x}' for v in packed[i:i + 16])
        lines.append(f'    {chunk},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def write_preview(packed, width, height, path):
    from PIL import Image

    bytes_per_row = (width + 7) // 8
    pixels = bytearray()
    for y in range(height):
        for x in range(width):
            byte = packed[y * bytes_per_row + x // 8]
            bit = (byte >> (7 - (x % 8))) & 1
            pixels.append(255 if bit else 0)
    img = Image.frombytes('L', (width, height), bytes(pixels))
    # Undo the packing rotation: 90 degrees clockwise.
    img = img.rotate(-90, expand=True)
    img.save(path)


def main():
    parser = argparse.ArgumentParser(
        usage='python3 scripts/build-logo.py <source.svg|png> '
              '[--size 120] [--output src/images/Logo120.h]')
    parser.add_argument('source')
    parser.add_argument('--size', type=int, default=120)
    parser.add_argument('--output', default='src/images/Logo120.h')
    parser.add_argument('--threshold', type=int, default=128)
    args = parser.parse_args()

    img = load_source_image(args.source, args.size)
    packed, width, height = pack_bitmap(img, args.threshold)

    output_path = args.output
    output_dir = os.path.dirname(os.path.abspath(output_path))
    os.makedirs(output_dir, exist_ok=True)
    array_name = os.path.splitext(os.path.basename(output_path))[0]

    header = render_header(packed, width, height,
                           os.path.basename(args.source), array_name)
    with open(output_path, 'w') as f:
        f.write(header)

    preview_path = os.path.join(output_dir, f'{array_name}.preview.png')
    write_preview(packed, width, height, preview_path)

    expected = height * math.ceil(width / 8)
    print(f'Wrote {output_path}')
    print(f'Wrote {preview_path}')
    print(f'{len(packed)} bytes (expected {expected})')
    if len(packed) != expected:
        print(f'WARNING: expected {expected} bytes for {width}x{height}', file=sys.stderr)


if __name__ == '__main__':
    main()
